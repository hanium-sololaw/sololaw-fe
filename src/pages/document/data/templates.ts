export type TemplateBlock =
  | { type: "title"; text: string }
  | { type: "heading"; text: string }
  | { type: "center"; text: string }
  | { type: "p"; text: string; indent?: boolean }
  | { type: "note"; text: string }
  | { type: "party"; rows: [label: string, value: string][] }
  | { type: "kv"; rows: [label: string, value: string, total?: boolean][] }
  | { type: "list"; rows: [left: string, right: string][] }
  | { type: "table"; head: string[]; rows: string[][] }
  | { type: "sign"; text: string }
  | { type: "court"; text: string };

export type DocumentTemplate = {
  id: string;
  category: string;
  label: string;
  badge: string;
  description: string;
  blocks: TemplateBlock[];
};

const title = (text: string): TemplateBlock => ({ type: "title", text });
const heading = (text: string): TemplateBlock => ({ type: "heading", text });
const p = (text: string): TemplateBlock => ({ type: "p", text });
const indent = (text: string): TemplateBlock => ({ type: "p", text, indent: true });
const kv = (...rows: [string, string, boolean?][]): TemplateBlock => ({ type: "kv", rows });
const list = (...rows: [string, string][]): TemplateBlock => ({ type: "list", rows });
const party = (...rows: [string, string][]): TemplateBlock => ({ type: "party", rows });

